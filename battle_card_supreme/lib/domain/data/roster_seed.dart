class _Blueprint {
  const _Blueprint({
    required this.id,
    required this.name,
    required this.pitch,
    required this.lore,
    required this.rarity,
    required this.role,
    required this.faction,
    required this.passiveName,
    required this.passiveDescription,
    required this.abilityId,
    required this.abilityName,
    required this.abilityDescription,
    required this.enCost,
    required this.cooldown,
    required this.mult,
    this.heal = 0,
    this.shield = 0,
    this.aoe = false,
    this.tags = const [],
    this.artSeed = 0,
  });

  final String id;
  final String name;
  final String pitch;
  final String lore;
  final Rarity rarity;
  final CardRole role;
  final Faction faction;
  final String passiveName;
  final String passiveDescription;
  final String abilityId;
  final String abilityName;
  final String abilityDescription;
  final int enCost;
  final int cooldown;
  final int mult;
  final int heal;
  final int shield;
  final bool aoe;
  final List<String> tags;
  final int artSeed;
}

CardDefinition _from(_Blueprint b) {
  final profile = profileFor(b.id);
  return CardDefinition(
    id: b.id,
    name: b.name,
    pitch: profile?.epithet ?? b.pitch,
    lore: profile?.story ?? b.lore,
    epithet: profile?.epithet ?? b.pitch,
    origin: profile?.origin ?? '',
    quote: profile?.quote ?? '',
    story: profile?.story ?? b.lore,
    rarity: b.rarity,
    role: b.role,
    faction: b.faction,
    stats: divideStats(rarity: b.rarity, role: b.role),
    passiveName: b.passiveName,
    passiveDescription: b.passiveDescription,
    active: AbilityDefinition(
      id: b.abilityId,
      name: b.abilityName,
      description: b.abilityDescription,
      enCost: b.enCost,
      cooldownTurns: b.cooldown,
      multiplierPercent: b.mult,
      healPercent: b.heal,
      shieldPercent: b.shield,
      isAoe: b.aoe,
    ),
    synergyTags: b.tags,
    artSeed: b.artSeed,
  );
}

