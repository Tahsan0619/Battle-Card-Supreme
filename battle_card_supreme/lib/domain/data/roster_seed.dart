final List<CardDefinition> kSeedRoster =
    List.unmodifiable(_blueprints.map(_from));

CardDefinition? cardById(String id) {
  for (final c in kSeedRoster) {
    if (c.id == id) return c;
  }
  return null;
}

List<CardDefinition> cardsByIds(List<String> ids) {
  return ids.map(cardById).whereType<CardDefinition>().toList();
}

Map<Rarity, int> rosterRarityCounts() {
  final map = {for (final r in Rarity.values) r: 0};
  for (final c in kSeedRoster) {
    map[c.rarity] = (map[c.rarity] ?? 0) + 1;
  }
  return map;
}
